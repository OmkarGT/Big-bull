import { useState } from 'react';
import { Link, NavLink, useNavigate } from 'react-router-dom';
import { LayoutDashboard, LogOut, PieChart, User, Menu, X, FlaskConical } from 'lucide-react';
import { useAuth } from '../context/AuthContext.jsx';
import { formatCurrency } from '../utils/formatCurrency.js';

const links = [
  { to: '/', label: 'Dashboard', icon: LayoutDashboard },
  { to: '/portfolio', label: 'Portfolio', icon: PieChart },
  { to: '/profile', label: 'Profile', icon: User },
];

export default function Navbar() {
  const { user, logout } = useAuth();
  const navigate = useNavigate();
  const [menuOpen, setMenuOpen] = useState(false);

  async function handleLogout() {
    await logout();
    navigate('/login', { replace: true });
  }

  const navItems = links.map(({ to, label, icon: Icon }) => (
    <NavLink
      key={to}
      to={to}
      end={to === '/'}
      onClick={() => setMenuOpen(false)}
      className={({ isActive }) =>
        `flex items-center gap-2 rounded-lg px-3 py-2 text-sm font-medium transition ${
          isActive ? 'bg-ink-900 text-white' : 'text-ink-700 hover:bg-ink-100'
        }`
      }
    >
      <Icon className="h-4 w-4" />
      {label}
    </NavLink>
  ));

  return (
    <header className="sticky top-0 z-40 border-b border-ink-200 bg-white/90 backdrop-blur">
      <div className="mx-auto max-w-7xl px-4 sm:px-6">
        <div className="flex h-16 items-center justify-between gap-4">
          <Link to="/" className="flex items-center gap-2.5 shrink-0">
            <img src="/logo.svg" alt="Big Bull logo" className="h-9 w-9" />
            <span className="leading-tight">
              <span className="block text-base font-black tracking-tight text-ink-900">BIG BULL</span>
              <span className="flex items-center gap-1 text-[10px] font-semibold uppercase tracking-wider text-bull-600">
                <FlaskConical className="h-3 w-3" /> Paper Trading
              </span>
            </span>
          </Link>

          {/* Desktop navigation */}
          <nav className="hidden items-center gap-1 md:flex">{navItems}</nav>

          <div className="hidden items-center gap-3 md:flex">
            <div className="text-right">
              <p className="text-xs text-ink-500">Virtual cash</p>
              <p className="text-sm font-bold text-ink-900">
                {formatCurrency(user?.virtual_balance ?? 0)}
              </p>
            </div>
            <button type="button" onClick={handleLogout} className="bb-btn-ghost">
              <LogOut className="h-4 w-4" /> Logout
            </button>
          </div>

          {/* Mobile toggle */}
          <button
            type="button"
            className="rounded-lg border border-ink-200 p-2 text-ink-700 md:hidden"
            onClick={() => setMenuOpen((open) => !open)}
            aria-label="Toggle navigation menu"
            aria-expanded={menuOpen}
          >
            {menuOpen ? <X className="h-5 w-5" /> : <Menu className="h-5 w-5" />}
          </button>
        </div>

        {/* Mobile navigation */}
        {menuOpen && (
          <div className="border-t border-ink-200 py-3 md:hidden">
            <nav className="flex flex-col gap-1">{navItems}</nav>

            <div className="mt-3 flex items-center justify-between rounded-lg bg-ink-50 px-3 py-2">
              <div>
                <p className="text-xs text-ink-500">Virtual cash</p>
                <p className="text-sm font-bold text-ink-900">
                  {formatCurrency(user?.virtual_balance ?? 0)}
                </p>
              </div>
              <button type="button" onClick={handleLogout} className="bb-btn-ghost">
                <LogOut className="h-4 w-4" /> Logout
              </button>
            </div>
          </div>
        )}
      </div>

      <div className="border-t border-ink-200 bg-ink-50">
        <p className="mx-auto max-w-7xl px-4 py-1.5 text-[11px] text-ink-500 sm:px-6">
          Simulated market &middot; virtual money only &middot; prices are generated by a local demo
          engine and are not real NSE/BSE quotes.
        </p>
      </div>
    </header>
  );
}
