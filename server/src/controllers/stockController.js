import { query, queryOne } from '../config/db.js';
import { notFound } from '../utils/errors.js';
import { validateStockId } from '../utils/validation.js';

const round2 = (value) => Math.round((value + Number.EPSILON) * 100) / 100;

/** Attach price, absolute change and percentage change to a stock row. */
function withChange(stock) {
  const currentPrice = round2(Number(stock.current_price));
  const previousPrice = round2(Number(stock.previous_price));
  const change = round2(currentPrice - previousPrice);
  const changePercent = previousPrice > 0 ? round2((change / previousPrice) * 100) : 0;

  return {
    id: stock.id,
    symbol: stock.symbol,
    company_name: stock.company_name,
    current_price: currentPrice,
    previous_price: previousPrice,
    change,
    change_percent: changePercent,
    is_positive: change >= 0,
    updated_at: stock.updated_at,
  };
}

/** GET /api/stocks - all 12 simulated stocks. */
export async function listStocks(_req, res) {
  const rows = await query(
    `SELECT id, symbol, company_name, current_price, previous_price, updated_at
       FROM stocks
      ORDER BY symbol ASC`
  );

  const stocks = rows.map(withChange);

  res.json({
    success: true,
    market: {
      name: 'Big Bull Simulated Market',
      status: 'SIMULATED',
      is_open: true, // the demo market never closes
      note: 'Prices are generated by a local random-walk engine. Not real NSE/BSE data.',
      last_tick: rows[0]?.updated_at ?? null,
    },
    count: stocks.length,
    stocks,
  });
}

/** GET /api/stocks/:id */
export async function getStock(req, res) {
  const id = validateStockId(req.params.id);

  const stock = await queryOne(
    `SELECT id, symbol, company_name, current_price, previous_price, updated_at
       FROM stocks
      WHERE id = ?`,
    [id]
  );

  if (!stock) throw notFound('Stock not found');

  res.json({
    success: true,
    stock: withChange(stock),
    disclaimer: 'Simulated price - demo market only.',
  });
}

/** GET /api/stocks/:id/history - recent simulated ticks for the chart. */
export async function getStockHistory(req, res) {
  const id = validateStockId(req.params.id);
  const limit = Math.min(Math.max(Number(req.query.limit) || 60, 1), 300);

  const stock = await queryOne('SELECT id, symbol, company_name FROM stocks WHERE id = ?', [id]);
  if (!stock) throw notFound('Stock not found');

  // Fetch the most recent rows, then flip them into chronological order.
  const rows = await query(
    `SELECT price, recorded_at
       FROM price_history
      WHERE stock_id = ?
      ORDER BY recorded_at DESC, id DESC
      LIMIT ?`,
    [id, limit]
  );

  const history = rows
    .map((row) => ({
      price: round2(Number(row.price)),
      recorded_at: row.recorded_at,
    }))
    .reverse();

  res.json({
    success: true,
    stock: { id: stock.id, symbol: stock.symbol, company_name: stock.company_name },
    count: history.length,
    history,
    disclaimer: 'Simulated price history generated by the Big Bull price engine.',
  });
}
